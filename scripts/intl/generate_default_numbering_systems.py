"""Generate the default numbering system of each locale for Broiler.JS's Intl, from Unicode CLDR.

    python3 scripts/intl/generate_default_numbering_systems.py <cldr-numbers-full-47.0.0.tgz>

The input is the cldr-numbers-full package of the cldr-json release, as the npm registry serves it
(https://registry.npmjs.org/cldr-numbers-full/-/cldr-numbers-full-47.0.0.tgz); the script refuses any
other bytes. Each locale's main/<locale>/numbers.json in that release carries its resolved
`defaultNumberingSystem`, CLDR's own inheritance applied.

The output, Broiler.JS/Broiler.JavaScript.BuiltIns/Intl/JSIntlDefaultNumberingSystems.g.cs, holds the
locales whose default differs from the one their parent gives when the tag is truncated at its last
subtag, the lookup the engine performs; a locale it does not list takes its parent's default, and the
root's is "latn". So the engine answers every CLDR locale as CLDR does. Run with the same input, it
writes the same bytes.

The data is CLDR's, under the Unicode License v3, which THIRD_PARTY_NOTICES.md carries. Milestone
SJL-9 of the shared JavaScript libraries programme moves locale data to the shared libraries; until
then this table is the engine's.
"""

import base64
import hashlib
import json
import os
import re
import sys
import tarfile

CLDR_VERSION = "47.0.0"
PACKAGE = "cldr-numbers-full"
# The npm registry's integrity for cldr-numbers-full@47.0.0.
INTEGRITY = "sha512-5OXUfjiAdXYuVD4XlaQe++WKBVmI1bkKxO0uWJMpbokzgcJ30vhFzcX5WsnZMtoZuhEpOt5KubCJaxaHPj5XTQ=="
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "Broiler.JS",
                   "Broiler.JavaScript.BuiltIns", "Intl", "JSIntlDefaultNumberingSystems.g.cs")


def read_defaults(archive):
    raw = open(archive, "rb").read()
    integrity = "sha512-" + base64.b64encode(hashlib.sha512(raw).digest()).decode("ascii")
    if integrity != INTEGRITY:
        raise SystemExit("%s is not %s@%s: integrity %s" % (archive, PACKAGE, CLDR_VERSION, integrity))
    defaults = {}
    with tarfile.open(archive) as members:
        for member in members.getmembers():
            found = re.match(r"package/main/([^/]+)/numbers\.json$", member.name)
            if found:
                locale = found.group(1)
                data = json.load(members.extractfile(member))
                defaults[locale] = data["main"][locale]["numbers"]["defaultNumberingSystem"]
    return defaults


def lookup(table, locale):
    """The engine's lookup: the tag, then each truncation of it, then the root's "latn"."""
    subtags = locale.split("-")
    while subtags:
        tag = "-".join(subtags)
        if tag in table:
            return table[tag]
        subtags.pop()
    return "latn"


def overrides(defaults):
    table = {}
    # Parents before children, so a child is compared with what the table already gives its parent.
    for locale in sorted(defaults, key=lambda tag: (tag.count("-"), tag)):
        if lookup(table, locale) != defaults[locale]:
            table[locale] = defaults[locale]
    for locale, system in defaults.items():
        if lookup(table, locale) != system:
            raise SystemExit("the table does not reproduce %s=%s" % (locale, system))
    return table


def render(table, count):
    lines = [
        "// <auto-generated>",
        "// Generated by scripts/intl/generate_default_numbering_systems.py from the Unicode CLDR %s package" % CLDR_VERSION,
        "// %s (%s): the defaultNumberingSystem of each of its %d locales, kept where it differs from the" % (PACKAGE, INTEGRITY, count),
        "// default its truncated parent gives. Copyright (c) 2004-2025 Unicode, Inc., Unicode License v3",
        "// (SPDX-License-Identifier: Unicode-3.0), whose notice THIRD_PARTY_NOTICES.md carries.",
        "// Do not edit: run the generator again.",
        "// </auto-generated>",
        "",
        "namespace Broiler.JavaScript.BuiltIns.Intl;",
        "",
        "internal static class JSIntlDefaultNumberingSystems",
        "{",
        "    internal const string CldrVersion = \"%s\";" % CLDR_VERSION,
        "",
        "    private static readonly System.Collections.Generic.Dictionary<string, string> Overrides =",
        "        new(System.StringComparer.OrdinalIgnoreCase)",
        "        {",
    ]
    lines += ["            [\"%s\"] = \"%s\"," % (locale, table[locale]) for locale in sorted(table)]
    lines += [
        "        };",
        "",
        "    // CLDR's default numbering system for a language tag: its language, script and region subtags",
        "    // (any extension or private use removed), then each truncation of them, then the root's \"latn\".",
        "    internal static string Of(string localeTag)",
        "    {",
        "        if (string.IsNullOrEmpty(localeTag))",
        "            return \"latn\";",
        "",
        "        var tag = localeTag;",
        "        var singleton = tag.IndexOf(\"-u-\", System.StringComparison.OrdinalIgnoreCase);",
        "        foreach (var marker in new[] { \"-t-\", \"-x-\" })",
        "        {",
        "            var at = tag.IndexOf(marker, System.StringComparison.OrdinalIgnoreCase);",
        "            if (at >= 0 && (singleton < 0 || at < singleton))",
        "                singleton = at;",
        "        }",
        "        if (singleton >= 0)",
        "            tag = tag[..singleton];",
        "",
        "        while (tag.Length > 0)",
        "        {",
        "            if (Overrides.TryGetValue(tag, out var system))",
        "                return system;",
        "            var last = tag.LastIndexOf('-');",
        "            tag = last < 0 ? string.Empty : tag[..last];",
        "        }",
        "",
        "        return \"latn\";",
        "    }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    defaults = read_defaults(sys.argv[1])
    table = overrides(defaults)
    with open(OUT, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(render(table, len(defaults)))
    print("%d CLDR %s locales; %d kept, %d of them not latn" % (
        len(defaults), CLDR_VERSION, len(table), sum(1 for v in table.values() if v != "latn")))


if __name__ == "__main__":
    main()
